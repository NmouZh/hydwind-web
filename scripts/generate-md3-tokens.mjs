import { writeFileSync } from 'node:fs';
import {
  Hct,
  MaterialDynamicColors,
  SchemeFidelity,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities';

const seed = process.env.MD3_SEED ?? '#2F5BEA';
const output = 'src/styles/md3-tokens.css';

const roles = [
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
  'background',
  'onBackground',
  'surface',
  'onSurface',
  'surfaceVariant',
  'onSurfaceVariant',
  'surfaceDim',
  'surfaceBright',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'outline',
  'outlineVariant',
  'inverseSurface',
  'inverseOnSurface',
  'inversePrimary',
  'surfaceTint',
  'shadow',
  'scrim',
];

const colors = new MaterialDynamicColors();

const kebab = (value) =>
  value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

const declarations = (isDark) => {
  const scheme = new SchemeFidelity(
    Hct.fromInt(argbFromHex(seed)),
    isDark,
    0
  );

  return roles
    .map((role) => {
      const argb = colors[role]().getArgb(scheme);
      return `  --md-sys-color-${kebab(role)}: ${hexFromArgb(argb)};`;
    })
    .join('\n');
};

const css = `/* Generated by scripts/generate-md3-tokens.mjs.
 * Seed: ${seed} · Scheme: SchemeFidelity · Contrast: 0
 * Regenerate with: bun run tokens
 */

:root {
  color-scheme: light;
${declarations(false)}
}

[data-theme='dark'] {
  color-scheme: dark;
${declarations(true)}
}
`;

writeFileSync(output, css);
console.log(`Wrote ${output} from ${seed}`);
